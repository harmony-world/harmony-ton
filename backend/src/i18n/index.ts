export function resolveLocale(raw: string | null | undefined): Locale {
  const normalized = (raw ?? "").trim().toLowerCase();
  if (!normalized) return DEFAULT_LOCALE;
  for (const part of normalized.split(",")) {
    const code = part.trim().split(";")[0]?.split("-")[0];
    if (code === "ru" || code === "en" || code === "hi") return code;
  }
  return FOREIGN_LOCALE;
}

export function t(locale: Locale | string | null | undefined, key: string, vars: TranslationVars = {}): string {
  const resolvedLocale = resolveLocale(locale);
  const template = messages[resolvedLocale][key] ?? messages[FOREIGN_LOCALE][key] ?? messages[DEFAULT_LOCALE][key] ?? key;
  return template.replace(/\{\{(\w+)\}\}/g, (_match: string, name: string) => String(vars[name] ?? ""));
}
